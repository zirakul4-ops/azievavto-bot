def main():
    state = json.loads(STATE_FILE.read_text(encoding="utf-8")) if STATE_FILE.exists() else {"posted": []}
    i = state.get("tip_index", 0) % len(TIPS)
    text = TIPS[i] + FOOTER
    print(text)

    if os.getenv("DRY_RUN", "").strip().lower() in ("1", "true", "yes"):
        print("DRY_RUN: в канал не отправлено.")
        return

    token = os.environ["TELEGRAM_BOT_TOKEN"].strip()
    chat = re.sub(r"^(https?://)?(www\.)?(t\.me|telegram\.me)/", "", os.environ["TELEGRAM_CHANNEL"].strip()).strip("/ ")
    if not chat.startswith("@") and not re.fullmatch(r"-?\d+", chat):
        chat = "@" + chat
    r = requests.post(f"https://api.telegram.org/bot{token}/sendMessage",
                      data={"chat_id": chat, "text": text, "parse_mode": "HTML",
                            "disable_web_page_preview": "true"}, timeout=60)
    if not r.ok or not r.json().get("ok"):
        sys.exit(f"Telegram ответил ошибкой: {r.status_code} {r.text[:500]}")
    msg_id = r.json()["result"]["message_id"]
    post_to_vk(text, f"https://t.me/{chat[1:]}/{msg_id}" if chat.startswith("@") else None)

    state["tip_index"] = i + 1
    STATE_FILE.write_text(json.dumps(state, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Опубликован полезный пост №{i + 1} из {len(TIPS)}")


if __name__ == "__main__":
    main()
